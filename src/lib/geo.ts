// 지역 기준 좌표 사전 — 각 지역의 **대표 행정기관**(도청/시청/구청/군청) 인근 대표점 기준.
// 키: ① 시도 단독("서울") ② 복합 "{시도} {시군구}"("부산 해운대구") ③ 서울 구 단독(레거시 호환, "마포구").
// 특정 지역 선택 시 이 기준점 반경 3km를 적용한다 (확정: 2026-07-10).
const REGION_CENTERS: Record<string, LatLng> = (() => {
  const out: Record<string, LatLng> = { ...SIDO_COORDS };
  for (const [sido, guguns] of Object.entries(GUGUN_CENTERS)) {
    for (const [gugun, c] of Object.entries(guguns)) {
      out[`${sido} ${gugun}`] = c;
      // 서울 구 단독 키는 레거시(기존 시드·URL) 호환용으로 유지 — 타 시도는 구명 중복(중구 등)으로 미등재
      if (sido === "서울") out[gugun] = c;
    }
  }
  return out;
})();

// 시도 17개 대분류 — 전국 지도 클러스터(지역별 캠페인 건수) 집계·마커 좌표용.
const SIDO_LABELS = [
  "서울", "경기", "인천", "부산", "대구", "광주", "대전", "울산", "세종",
  "강원", "충북", "충남", "전북", "전남", "경북", "경남", "제주",
] as const;

export const SIDO_CENTERS: Record<string, LatLng> = Object.fromEntries(
  SIDO_LABELS.map((k) => [k, REGION_CENTERS[k]]),
);

// 좌표 → 최근접 시도 라벨. 매장 area 문자열은 동네 라벨("성수동" 등)이라
// 시도 매칭이 불가능하므로 클러스터 집계는 좌표 기반으로 한다.
// 시도 대표점만 비교하면 경계 지역(광명 등)이 인접 시도로 오귀속되므로,
// 전 시군구 기준점 중 최근접의 소속 시도를 반환한다 (2026-07-10 정밀화).
const NEAREST_POOL: Array<{ sido: string; c: LatLng }> = (() => {
  const pool: Array<{ sido: string; c: LatLng }> = SIDO_LABELS.map((k) => ({ sido: k, c: SIDO_COORDS[k] }));
  for (const [sido, guguns] of Object.entries(GUGUN_CENTERS)) {
    for (const c of Object.values(guguns)) pool.push({ sido, c });
  }
  return pool;
})();

export function nearestSido(p: LatLng): string {
  let best = SIDO_LABELS[0] as string;
  let bestD = Infinity;
  for (const { sido, c } of NEAREST_POOL) {
    const d = haversineM(p, c);
    if (d < bestD) {
      bestD = d;
      best = sido;
    }
  }
  return best;
}

// 지역 라벨 → 기준 좌표.
// ① 정확 일치(시도·복합 "{시도} {시군구}"·서울 구 레거시) ② 단독 시군구 라벨 → 소속 시도의 복합 키
// ③ 부분 포함 일치 ④ 소속 시도 대표점 폴백 ⑤ null.
// 단독 "중구"처럼 시도 간 중복되는 라벨은 findSido가 REGIONS 순서상 첫 시도로 해석한다(결정적).
export function regionCenter(label: string): LatLng | null {
  if (!label) return null;
  if (REGION_CENTERS[label]) return REGION_CENTERS[label];
  const sido = findSido(label);
  if (sido && REGION_CENTERS[`${sido} ${label}`]) return REGION_CENTERS[`${sido} ${label}`];
  const hit = Object.keys(REGION_CENTERS).find((k) => label.includes(k) || k.includes(label));
  if (hit) return REGION_CENTERS[hit];
  if (sido && REGION_CENTERS[sido]) return REGION_CENTERS[sido];
  return null;
}
